#!/usr/bin/env node
/**
 * Demo photos (specs/demo-photos.md): turn downloaded originals into the same
 * files the editor makes on a phone, with the same rules from packages/core
 * (photoLimits, widthsFor): 480, 960 and 1440 px WebP (no upscaling), quality
 * stepped down to each size target, each file under the 300 KB limit. The
 * canvas redraw drops EXIF. Writes apps/web/public/demo-photos/<name>/<w>.webp
 * and apps/web/src/data/demo-photos.ts (sizes and credits).
 *
 *   node scripts/demo-photos.mjs <originals dir> <manifest.json>
 *
 * manifest.json: { "<name>": { "file": "<name>.jpg", "credit": { title, author, source_url, licence, licence_url } } }
 * Run by hand when the demo photos change; the outputs are committed.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { existsSync } from "node:fs";
import { photoLimits, widthsFor, photoLicences, staticPhotoUrls } from "../packages/core/src/media.ts";

const ROOT = new URL("..", import.meta.url).pathname;
const [srcDir, manifestPath] = process.argv.slice(2);
if (!srcDir || !manifestPath) throw new Error("usage: node scripts/demo-photos.mjs <originals dir> <manifest.json>");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const OUT = join(ROOT, "apps/web/public/demo-photos");

const browser = await chromium.launch(process.env.PW_CHROMIUM_PATH ? { executablePath: process.env.PW_CHROMIUM_PATH } : {});
const page = await browser.newPage();
await page.setContent("<!doctype html><title>shrink</title>");

const result = {};
for (const [name, item] of Object.entries(manifest)) {
  if (!/^[a-z0-9](-?[a-z0-9])*$/.test(name)) throw new Error(`bad photo name ${name}`);
  if (!photoLicences.includes(item.credit.licence)) throw new Error(`${name}: licence ${item.credit.licence} is not allowed`);
  if (!existsSync(join(srcDir, item.file))) throw new Error(`${name}: ${item.file} not found`);
  const original = readFileSync(join(srcDir, item.file)).toString("base64");
  // widthsFor needs the original width: read it first, then encode.
  const size = await page.evaluate(async (b64) => {
    const bitmap = await createImageBitmap(await (await fetch(`data:image/jpeg;base64,${b64}`)).blob());
    return { w: bitmap.width, h: bitmap.height };
  }, original);
  const widths = widthsFor(size.w);
  const encoded = await page.evaluate(
    async ({ b64, limits, widthsList }) => {
      const bitmap = await createImageBitmap(await (await fetch(`data:image/jpeg;base64,${b64}`)).blob(), { imageOrientation: "from-image" });
      const out = [];
      for (const w of widthsList) {
        const cw = Math.min(w, bitmap.width);
        const ch = Math.round((bitmap.height * cw) / bitmap.width);
        const canvas = document.createElement("canvas");
        canvas.width = cw;
        canvas.height = ch;
        canvas.getContext("2d").drawImage(bitmap, 0, 0, cw, ch);
        let file = null;
        for (let q = 0.82; q >= 0.25; q -= 0.08) {
          file = await new Promise((r) => canvas.toBlob(r, "image/webp", q));
          if (file.size <= limits.targetBytes[w]) break;
        }
        if (!file || file.size > limits.fileBytes) throw new Error(`width ${w}: ${file?.size} B over the limit`);
        const bytes = new Uint8Array(await file.arrayBuffer());
        let s = "";
        for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
        out.push({ w, width: cw, height: ch, b64: btoa(s) });
      }
      return out;
    },
    { b64: original, limits: photoLimits, widthsList: widths },
  );
  mkdirSync(join(OUT, name), { recursive: true });
  let total = 0;
  for (const f of encoded) {
    const buf = Buffer.from(f.b64, "base64");
    if (buf.includes(Buffer.from("Exif"))) throw new Error(`${name}/${f.w}: EXIF left in the file`);
    writeFileSync(join(OUT, name, `${f.w}.webp`), buf);
    total += buf.length;
  }
  const top = encoded[encoded.length - 1];
  result[name] = { path: `demo-photos/${name}`, width: top.width, height: top.height, bytes: total, files: encoded.map((f) => [f.w, Buffer.from(f.b64, "base64").length]), credit: item.credit };
  console.log(`${name.padEnd(26)} ${String(size.w).padStart(5)} px → ${encoded.map((f) => `${f.w}: ${(Buffer.from(f.b64, "base64").length / 1024).toFixed(1)} KB`).join(", ")}`);
}
await browser.close();

const lines = [
  "/**",
  " * DEMO PHOTOS — generated by scripts/demo-photos.mjs. Do not edit by hand.",
  " * Openly licensed photos (CC0, Public Domain Mark or CC BY) for the fake",
  " * Kinigi Hills demo, resized and compressed. Files: apps/web/public/demo-photos/.",
  " * Credits: CREDITS.md and the site's \"Photo credits\" page.",
  " */",
  'import type { PhotoCredit } from "@getkaze/core";',
  "",
  "/** src and srcset come from core staticPhotoUrls (same rule as the guest site). */",
  "export type DemoPhoto = { path: string; width: number; height: number; bytes: number; src: string; srcset: string; credit: PhotoCredit };",
  "",
  `export const demoPhotos = ${JSON.stringify(Object.fromEntries(Object.entries(result).map(([k, v]) => [k, { path: v.path, width: v.width, height: v.height, bytes: v.bytes, ...staticPhotoUrls(v.path, "webp", v.width), credit: v.credit }])), null, 2)} as const satisfies Record<string, DemoPhoto>;`,
  "",
  "export type DemoPhotoName = keyof typeof demoPhotos;",
  "",
];
writeFileSync(join(ROOT, "apps/web/src/data/demo-photos.ts"), lines.join("\n"));
const all = Object.values(result).reduce((n, r) => n + r.bytes, 0);
console.log(`\n${Object.keys(result).length} photos, ${(all / 1024).toFixed(0)} KB in apps/web/public/demo-photos`);
